"""Regenerate API_SAMPLE_RESPONSES.md from real calls against the app (LLM extraction; needs LLM_API_KEY).

    python -m scripts.generate_api_samples
"""
from __future__ import annotations

import json
import tempfile
from dataclasses import replace
from pathlib import Path

from fastapi import FastAPI
from fastapi.testclient import TestClient

from app.api.routes import router
from app.config import get_settings
from app.memory.service import MemoryEngine

TURNS = [
    "My preferred language is Kannada.",
    "I moved to Pune last month for a new job as a data analyst at a fintech startup.",
    "Please don't call me before 11 AM, I have standups every morning.",
]
FOLLOW_UP = "Can you suggest a good time to call me, and should we talk in my language?"


def main() -> None:
    with tempfile.TemporaryDirectory() as tmp:
        settings = replace(get_settings(), database_path=str(Path(tmp) / "samples.db"), extractor="llm", enable_llm_response=False)
        app = FastAPI()
        app.state.memory_engine = MemoryEngine(settings)
        app.include_router(router)
        client = TestClient(app)
        sections: list[tuple[str, str, str]] = []

        def record(title: str, method: str, path: str, body: dict | None = None) -> dict:
            response = client.request(method, path, json=body)
            response.raise_for_status()
            request = f"{method} {path}" + (f"\nContent-Type: application/json\n\n{json.dumps(body, indent=2)}" if body else "")
            sections.append((title, request, json.dumps(response.json(), indent=2)))
            return response.json()

        try:
            record("Health and active backends", "GET", "/health")
            for text in TURNS:
                record("Send a turn", "POST", "/sessions/demo/turns", {"user_message": text, "expose_memory": True})
            # The flush endpoint waits 3 s; LLM extraction of three turns can take longer, so wait here first.
            app.state.memory_engine.drain_background(timeout_seconds=180)
            record("Wait for background extraction", "POST", "/sessions/demo/flush")
            record("List extracted memories", "GET", "/sessions/demo/memories?status=active")
            record("Recall at a later turn", "POST", "/sessions/demo/turns", {"user_message": FOLLOW_UP, "expose_memory": True})
        finally:
            app.state.memory_engine.shutdown()

    lines = [
        "# API sample responses",
        "",
        "Generated by `python -m scripts.generate_api_samples` against a fresh database, with LLM extraction",
        f"(`{settings.llm_model}`) and the rule-based responder. Memory ids, timestamps and latencies vary per run.",
        "Extraction runs in a background worker, so a turn's own memories appear from the next turn onward.",
        "",
    ]
    for number, (title, request, response) in enumerate(sections, start=1):
        lines += [f"## {number}. {title}", "", "```http", request, "```", "", "```json", response, "```", ""]
    Path("API_SAMPLE_RESPONSES.md").write_text("\n".join(lines).rstrip("\n") + "\n", encoding="utf-8", newline="\n")
    print("wrote API_SAMPLE_RESPONSES.md")


if __name__ == "__main__":
    main()
